/// <reference types="vite/client" />
// The Node-test typecheck project loads only Node types, and the website's pricing module reads
// import.meta.env, so the Vite types are pulled in here, for this file only.
// The iPhone app's service step (ios/SmarterDog/BookingServices.swift) mirrors the website's.
// Every price a customer sees on the website comes from the PRICING table in
// src/constants/salon.ts. This test generates ios/AuthCoreTests/service-prices.json from the
// REAL website functions (the label for every service and size, and which services are
// offered), fails when that file is stale, and checks the Swift table, descriptions, "from"
// marks and the sentence above the tiles against the website.
//
// To refresh after a deliberate price or service change:
//   UPDATE_IOS_SERVICE_PRICES=1 npx vitest run src/security/iosBookingServices.test.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { FROM_PRICED_SERVICES, PRICING, SERVICES } from "../constants/salon";
import { getAllowedServicesForSize, getServicePriceLabel } from "../engine/bookingRules";

const root = join(__dirname, "..", "..");
const JSON_PATH = join(root, "ios/AuthCoreTests/service-prices.json");
const swift = readFileSync(join(root, "ios/SmarterDog/BookingServices.swift"), "utf8");
const tsx = readFileSync(join(root, "src/components/customer/booking/ServiceSelection.tsx"), "utf8");
const SIZES = ["small", "medium", "large"] as const;

function build() {
  const labels: Record<string, Record<string, string | null>> = {};
  for (const service of SERVICES) {
    labels[service.id] = {};
    for (const size of SIZES) {
      const label = getServicePriceLabel(service.id, size);
      labels[service.id][size] = label === "N/A" ? null : label;
    }
  }
  const offered: Record<string, string[]> = {};
  for (const size of SIZES) offered[size] = getAllowedServicesForSize(size).map((service) => service.id);
  return {
    note: "Generated by src/security/iosBookingServices.test.ts from the website's own functions. Do not edit by hand.",
    names: Object.fromEntries(SERVICES.map((service) => [service.id, service.name])),
    labels,
    offered,
  };
}

describe("iPhone service step mirrors the website", () => {
  it("has a price-label file that is up to date with the website", () => {
    const expected = build();
    if (process.env.UPDATE_IOS_SERVICE_PRICES === "1") {
      writeFileSync(JSON_PATH, `${JSON.stringify(expected, null, 1)}\n`);
    }
    expect(JSON.parse(readFileSync(JSON_PATH, "utf8")), "run with UPDATE_IOS_SERVICE_PRICES=1").toEqual(expected);
  });

  it("has a file that exercises a fixed price, a from price and a size a service is not offered for", () => {
    const { labels } = build();
    expect(labels["puppy-groom"].small).toBe("£38");
    expect(labels["full-groom"].medium).toBe("£46+");
    expect(labels["puppy-groom"].large).toBeNull();
  });

  it("uses the website's price table", () => {
    const table = swift.slice(swift.indexOf("static let guidePricePence"));
    const block = table.slice(0, table.indexOf("\n    ]") + 6);
    const rows = [...block.matchAll(/^\s+"([a-z-]+)": \[(.*)\],$/gm)];
    const swiftPrices = Object.fromEntries(
      rows.map((row) => [
        row[1],
        Object.fromEntries([...row[2].matchAll(/\.(small|medium|large): (\d+)/g)].map((pair) => [pair[1], Number(pair[2])])),
      ]),
    );
    const website = Object.fromEntries(
      Object.entries(PRICING).map(([id, bySize]) => [
        id,
        Object.fromEntries(Object.entries(bySize).filter(([, pence]) => pence != null)),
      ]),
    );
    expect(swiftPrices).toEqual(website);
  });

  it("marks the same services as from-priced", () => {
    const line = swift.match(/static let fromPriced: Set<String> = \[(.*)\]/)?.[1] ?? "";
    const ids = [...line.matchAll(/"([a-z-]+)"/g)].map((match) => match[1]);
    expect(new Set(ids)).toEqual(new Set(FROM_PRICED_SERVICES));
  });

  it("uses the website's descriptions, the website's id for each name, and the website's sentence", () => {
    const websiteBlock = tsx.slice(tsx.indexOf("const SERVICE_DESCRIPTIONS"), tsx.indexOf("};", tsx.indexOf("const SERVICE_DESCRIPTIONS")));
    const websiteDescriptions = Object.fromEntries(
      [...websiteBlock.matchAll(/"([a-z-]+)": "([^"]*)"/g)].map((match) => [match[1], match[2]]),
    );
    const block = swift.slice(swift.indexOf("static let descriptions"));
    const swiftDescriptions = Object.fromEntries(
      [...block.slice(0, block.indexOf("\n    ]") + 6).matchAll(/^\s+"([a-z-]+)": "([^"]*)",$/gm)].map((match) => [match[1], match[2]]),
    );
    expect(swiftDescriptions).toEqual(websiteDescriptions);

    // Each Swift case maps to the website's id for the same name.
    const cases = [...swift.matchAll(/case \.(\w+): "([a-z-]+)"/g)].map((match) => match[2]);
    expect(new Set(cases)).toEqual(new Set(SERVICES.map((service) => service.id)));

    const sentence = swift.match(/startingPriceNote =\s*"([^"]*)"/)?.[1];
    const website = tsx
      .match(/Choose a service for each pup\.[\s\S]*?extras\./)?.[0]
      .replace(/\s+/g, " ")
      .replace("&mdash;", "—");
    expect(sentence).toBe(website);
  });
});
