-- Cross-runtime capacity parity: PostgreSQL versus the browser engine.
--
-- The capacity rules exist in three runtimes (src/engine/capacity.ts, the Deno
-- mirror, and validate_booking_capacity() here). capacityParity.test.ts guards
-- the two TypeScript copies against each other and 035_capacity_behaviour
-- proves this trigger on its own terms, but nothing fed the SAME scenario to
-- the browser engine and to PostgreSQL until this file.
--
-- Scenarios come from src/engine/capacityParityFixtures.ts. There are two
-- kinds, asking different questions:
--
--   single      — canBookSlot() answers yes/no and PostgreSQL must match.
--   group#N     — findGroupedSlots() OFFERS an allocation and PostgreSQL must
--                 accept it. Every offer the engine makes is inserted here as
--                 a whole group. An offer the database refuses is the
--                 customer-facing failure this file exists to catch.
--   group#naive — the engine offered nothing; a straightforward placement is
--                 attempted anyway, to show whether the database would have
--                 accepted one (the engine being stricter costs bookings).
--
-- Each assertion encodes the database's OBSERVED behaviour, measured
-- 19 August 2026. src/engine/capacityParityFixtures.test.ts recomputes the
-- engine side and fails if this file drifts from it.
--
-- As of the fix for issue #664 there is NO divergence: all 162 cases agree,
-- and every allocation the engine offers is one the database accepts. The
-- TypeScript guard keeps an empty divergence register, so a future
-- disagreement has to be recorded deliberately rather than absorbed silently.
--
-- Cases 130-162 were added on 20 August 2026, covering blocked seats against
-- large dogs and grouped allocation onto blocked, extra-slot and mixed-size
-- days. They are generated by scripts/generate-capacity-parity-cases.ts, which
-- takes the engine's answer from src/engine/capacity.ts and OBSERVES the
-- database's by attempting the insert -- so a throws_ok here records what
-- PostgreSQL actually did, never what anyone assumed it would do.

